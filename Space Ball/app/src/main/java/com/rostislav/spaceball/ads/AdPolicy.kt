package com.rostislav.spaceball.ads

/**
 * Частота показу interstitial.
 *
 *  - Перемога   → реклама щоразу (перемоги рідкі, момент природний).
 *  - Поразка    → реклама лише після КОЖНОЇ ДРУГОЇ поразки,
 *                 бо програвати гравець буде часто, і реклама на кожен провал вбиває ретеншн.
 *
 * Лічильник поразок наскрізний (не скидається при зміні рівня), тому
 * послідовність показів рівна: провал, провал+реклама, провал, провал+реклама...
 */
object AdPolicy {

    private var lossCount = 0

    /** Викликати при програші. Повертає true, якщо саме зараз треба показати рекламу. */
    fun onLevelLost(): Boolean {
        lossCount++
        return lossCount % 2 == 0
    }

    /** Викликати при перемозі. Реклама показується завжди. */
    fun onLevelWon(): Boolean = true

    fun reset() {
        lossCount = 0
    }
}